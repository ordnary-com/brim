//! TypeScript types for the API contracts of Brim programs (`brim gen ts`).
//!
//! A backend written in Brim declares the types of its API once; this crate
//! writes the matching TypeScript declarations for a web frontend, so the
//! two cannot drift apart. The types describe Brim values as JSON:
//!
//! | Brim                         | TypeScript                                        |
//! |------------------------------|---------------------------------------------------|
//! | `i64`                        | `number`                                          |
//! | `bool`                       | `boolean`                                         |
//! | `string`                     | `string`                                          |
//! | `List[T]`                    | `T[]`                                             |
//! | `Map[string, V]`             | `Record<string, V>`                               |
//! | `Map[i64, V]`                | `Record<number, V>`                               |
//! | `Map[bool, V]`               | `Partial<Record<"true" \| "false", V>>`           |
//! | `Option[T]`                  | `T \| null`                                       |
//! | `Result[T, E]`               | `{ kind: "Ok"; value: T } \| { kind: "Err"; value: E }` |
//! | `struct P { x: i64 }`        | `interface P { x: number }`                       |
//! | `enum C { Red, Green }`      | `type C = "Red" \| "Green"`                       |
//! | `enum S { A(i64), B(i64, string), C }` | `type S = { kind: "A"; value: number } \| { kind: "B"; value: [number, string] } \| { kind: "C" }` |
//!
//! Generic structs and enums become generic TypeScript types.

use std::collections::{BTreeSet, HashMap};
use std::fmt::Write as _;

use brim_diagnostics::Diagnostic;
use brim_semantic::checked::CheckedProgram;
use brim_semantic::{Def, EnumId, StructId, Type};

/// The TypeScript declarations for the `pub` structs and enums of the
/// modules `export` selects, and for the types they use. `source` names the
/// program in the header comment.
pub fn generate(
    program: &CheckedProgram,
    export: impl Fn(usize) -> bool,
    source: &str,
) -> Result<String, Vec<Diagnostic>> {
    let mut generator = Generator {
        program,
        wanted: BTreeSet::new(),
    };
    for (i, s) in program.structs.iter().enumerate() {
        if s.public && export(s.module) {
            generator.want(Def::Struct(StructId(i)));
        }
    }
    for (i, e) in program.enums.iter().enumerate() {
        if e.public && e.module.is_some_and(&export) {
            generator.want(Def::Enum(EnumId(i)));
        }
    }

    // TypeScript has one namespace: types of different modules need
    // different names.
    let mut by_name: HashMap<&str, Item> = HashMap::new();
    let mut diags = Vec::new();
    for &item in &generator.wanted {
        let name = generator.item_name(item);
        if let Some(&other) = by_name.get(name) {
            diags.push(
                Diagnostic::error(format!(
                    "two exported types are named `{name}`: `{}` and `{}`",
                    generator.qualified(other),
                    generator.qualified(item)
                ))
                .with_code("G0001")
                .with_note("TypeScript declarations share one namespace")
                .with_help("rename one of the types"),
            );
        } else {
            by_name.insert(name, item);
        }
    }
    if !diags.is_empty() {
        return Err(diags);
    }

    let mut out = format!(
        "// TypeScript types for the API of {source}.\n\
         // Generated by `brim gen ts`; do not edit.\n\
         // i64 values become numbers: beyond 2^53 they lose precision.\n"
    );
    for &item in &generator.wanted {
        out.push('\n');
        match item {
            Item::Struct(id) => generator.write_struct(&mut out, id),
            Item::Enum(id) => generator.write_enum(&mut out, id),
        }
    }
    Ok(out)
}

/// A declaration to write, in declaration order (structs, then enums).
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
enum Item {
    Struct(usize),
    Enum(usize),
}

struct Generator<'a> {
    program: &'a CheckedProgram,
    wanted: BTreeSet<Item>,
}

impl Generator<'_> {
    /// Adds a declaration and everything its fields use.
    fn want(&mut self, def: Def) {
        let item = match def {
            Def::Struct(id) => Item::Struct(id.0),
            // `Option` and `Result` are written inline.
            Def::Enum(id) if id.0 >= 2 => Item::Enum(id.0),
            _ => return,
        };
        if !self.wanted.insert(item) {
            return;
        }
        let used: Vec<Type> = match item {
            Item::Struct(id) => self.program.structs[id]
                .fields
                .iter()
                .map(|f| f.ty)
                .collect(),
            Item::Enum(id) => self.program.enums[id]
                .variants
                .iter()
                .flat_map(|v| v.fields.iter().copied())
                .collect(),
        };
        for ty in used {
            self.want_type(ty);
        }
    }

    fn want_type(&mut self, ty: Type) {
        if let Type::Named(id) = ty {
            let named = self.program.types.get(id).clone();
            self.want(named.def);
            for arg in named.args {
                self.want_type(arg);
            }
        }
    }

    fn item_name(&self, item: Item) -> &str {
        match item {
            Item::Struct(id) => &self.program.structs[id].name,
            Item::Enum(id) => &self.program.enums[id].name,
        }
    }

    fn qualified(&self, item: Item) -> String {
        let module = match item {
            Item::Struct(id) => Some(self.program.structs[id].module),
            Item::Enum(id) => self.program.enums[id].module,
        };
        let name = self.item_name(item);
        match module.map(|m| self.program.modules[m].as_str()) {
            Some("") | None => name.to_string(),
            Some(module) => format!("{module}.{name}"),
        }
    }

    fn write_struct(&self, out: &mut String, id: usize) {
        let s = &self.program.structs[id];
        let _ = writeln!(
            out,
            "export interface {}{} {{",
            s.name,
            type_args(&s.type_params)
        );
        for field in &s.fields {
            let _ = writeln!(
                out,
                "  {}: {};",
                field.name,
                self.ts(field.ty, &s.type_params)
            );
        }
        out.push_str("}\n");
    }

    fn write_enum(&self, out: &mut String, id: usize) {
        let e = &self.program.enums[id];
        let _ = write!(out, "export type {}{} =", e.name, type_args(&e.type_params));
        if e.variants.iter().all(|v| v.fields.is_empty()) {
            let names: Vec<String> = e.variants.iter().map(|v| quote(&v.name)).collect();
            let _ = writeln!(out, " {};", names.join(" | "));
            return;
        }
        out.push('\n');
        for (i, v) in e.variants.iter().enumerate() {
            let value = match v.fields.as_slice() {
                [] => String::new(),
                [one] => format!("; value: {}", self.ts(*one, &e.type_params)),
                many => {
                    let parts: Vec<String> =
                        many.iter().map(|t| self.ts(*t, &e.type_params)).collect();
                    format!("; value: [{}]", parts.join(", "))
                }
            };
            let end = if i + 1 == e.variants.len() { ";" } else { "" };
            let _ = writeln!(out, "  | {{ kind: {}{value} }}{end}", quote(&v.name));
        }
    }

    /// A Brim type in TypeScript. `params` names the type parameters.
    fn ts(&self, ty: Type, params: &[String]) -> String {
        match ty {
            Type::I64 => "number".into(),
            Type::Bool => "boolean".into(),
            Type::String => "string".into(),
            Type::Void | Type::Error => "null".into(),
            Type::Param(i) => params[i as usize].clone(),
            Type::Named(id) => {
                let named = self.program.types.get(id);
                let args: Vec<String> = named.args.iter().map(|t| self.ts(*t, params)).collect();
                match named.def {
                    Def::List => {
                        if args[0].contains(['|', ' ']) {
                            format!("Array<{}>", args[0])
                        } else {
                            format!("{}[]", args[0])
                        }
                    }
                    Def::Map => match named.args[0] {
                        Type::I64 => format!("Record<number, {}>", args[1]),
                        Type::Bool => format!("Partial<Record<\"true\" | \"false\", {}>>", args[1]),
                        _ => format!("Record<string, {}>", args[1]),
                    },
                    Def::Enum(EnumId(0)) => format!("{} | null", args[0]),
                    Def::Enum(EnumId(1)) => format!(
                        "{{ kind: \"Ok\"; value: {} }} | {{ kind: \"Err\"; value: {} }}",
                        args[0], args[1]
                    ),
                    Def::Struct(StructId(i)) => {
                        format!("{}{}", self.program.structs[i].name, type_args(&args))
                    }
                    Def::Enum(EnumId(i)) => {
                        format!("{}{}", self.program.enums[i].name, type_args(&args))
                    }
                }
            }
        }
    }
}

fn type_args(args: &[String]) -> String {
    if args.is_empty() {
        String::new()
    } else {
        format!("<{}>", args.join(", "))
    }
}

fn quote(s: &str) -> String {
    format!("\"{s}\"")
}

