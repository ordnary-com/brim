//! TypeScript types for the API contracts of Brim programs (`brim gen ts`).
//!
//! A backend written in Brim declares the types of its API once; this crate
//! writes the matching TypeScript declarations for a web frontend, so the
//! two cannot drift apart. The types describe Brim values as JSON:
//!
//! | Brim                         | TypeScript                                        |
//! |------------------------------|---------------------------------------------------|
//! | `i64`, `f64`                 | `number`                                          |
//! | `bool`                       | `boolean`                                         |
//! | `string`                     | `string`                                          |
//! | `List[T]`                    | `T[]`                                             |
//! | `Map[string, V]`             | `Record<string, V>`                               |
//! | `Map[i64, V]` (any integer)  | `Record<number, V>`                               |
//! | `Map[bool, V]`               | `Partial<Record<"true" \| "false", V>>`           |
//! | `Option[T]`                  | `T \| null`                                       |
//! | `Result[T, E]`               | `{ kind: "Ok"; value: T } \| { kind: "Err"; value: E }` |
//! | `struct P { x: i64 }`        | `interface P { x: number }`                       |
//! | `enum C { Red, Green }`      | `type C = "Red" \| "Green"`                       |
//! | `enum S { A(i64), B(i64, string), C }` | `type S = { kind: "A"; value: number } \| { kind: "B"; value: [number, string] } \| { kind: "C" }` |
//!
//! Generic structs and enums become generic TypeScript types.
//!
//! With [`Options::angular`], the declarations are followed by an Angular
//! service for each module served with `serve_api`: a method per API
//! function that posts its parameters to `/api/<name>`.

use std::collections::{BTreeSet, HashMap};
use std::fmt::Write as _;

use brim_diagnostics::Diagnostic;
use brim_semantic::checked::CheckedProgram;
use brim_semantic::{Def, EnumId, StructId, Type};

/// What to write besides the type declarations.
#[derive(Clone, Copy, Debug, Default)]
pub struct Options {
    /// An Angular service per module served with `serve_api`.
    pub angular: bool,
}

/// The TypeScript declarations for the `pub` structs and enums of the
/// modules `export` selects, and for the types they use. `source` names the
/// program in the header comment.
pub fn generate(
    program: &CheckedProgram,
    export: impl Fn(usize) -> bool,
    source: &str,
    options: Options,
) -> Result<String, Vec<Diagnostic>> {
    let mut generator = Generator {
        program,
        wanted: BTreeSet::new(),
    };
    for (i, s) in program.structs.iter().enumerate() {
        if s.public && export(s.module) {
            generator.want(Def::Struct(StructId(i)));
        }
    }
    for (i, e) in program.enums.iter().enumerate() {
        if e.public && e.module.is_some_and(&export) {
            generator.want(Def::Enum(EnumId(i)));
        }
    }

    if options.angular {
        if program.api.is_empty() {
            return Err(vec![
                Diagnostic::error("no module is served with `serve_api`")
                    .with_code("G0002")
                    .with_note("`--angular` writes a client for the API functions of such a module")
                    .with_help("call `serve_api(module, request)` in the server"),
            ]);
        }
        for f in &program.api {
            for (_, ty) in &f.params {
                generator.want_type(*ty);
            }
            generator.want_type(f.ret);
        }
    }

    // TypeScript has one namespace: types of different modules need
    // different names.
    let mut by_name: HashMap<&str, Item> = HashMap::new();
    let mut diags = Vec::new();
    for &item in &generator.wanted {
        let name = generator.item_name(item);
        if let Some(&other) = by_name.get(name) {
            diags.push(
                Diagnostic::error(format!(
                    "two exported types are named `{name}`: `{}` and `{}`",
                    generator.qualified(other),
                    generator.qualified(item)
                ))
                .with_code("G0001")
                .with_note("TypeScript declarations share one namespace")
                .with_help("rename one of the types"),
            );
        } else {
            by_name.insert(name, item);
        }
    }
    if !diags.is_empty() {
        return Err(diags);
    }

    let mut out = format!(
        "// TypeScript types for the API of {source}.\n\
         // Generated by `brim gen ts`; do not edit.\n\
         // i64 values become numbers: beyond 2^53 they lose precision.\n"
    );
    if options.angular {
        out.push_str(
            "\n\
             import { Injectable, InjectionToken, inject } from '@angular/core';\n\
             import { HttpClient } from '@angular/common/http';\n\
             import { Observable } from 'rxjs';\n",
        );
    }
    for &item in &generator.wanted {
        out.push('\n');
        match item {
            Item::Struct(id) => generator.write_struct(&mut out, id),
            Item::Enum(id) => generator.write_enum(&mut out, id),
        }
    }
    if options.angular {
        generator.write_angular(&mut out);
    }
    Ok(out)
}

/// A declaration to write, in declaration order (structs, then enums).
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
enum Item {
    Struct(usize),
    Enum(usize),
}

struct Generator<'a> {
    program: &'a CheckedProgram,
    wanted: BTreeSet<Item>,
}

impl Generator<'_> {
    /// Adds a declaration and everything its fields use.
    fn want(&mut self, def: Def) {
        let item = match def {
            Def::Struct(id) => Item::Struct(id.0),
            // `Option` and `Result` are written inline.
            Def::Enum(id) if id.0 >= 2 => Item::Enum(id.0),
            _ => return,
        };
        if !self.wanted.insert(item) {
            return;
        }
        let used: Vec<Type> = match item {
            Item::Struct(id) => self.program.structs[id]
                .fields
                .iter()
                .map(|f| f.ty)
                .collect(),
            Item::Enum(id) => self.program.enums[id]
                .variants
                .iter()
                .flat_map(|v| v.fields.iter().copied())
                .collect(),
        };
        for ty in used {
            self.want_type(ty);
        }
    }

    fn want_type(&mut self, ty: Type) {
        if let Type::Named(id) = ty {
            let named = self.program.types.get(id).clone();
            self.want(named.def);
            for arg in named.args {
                self.want_type(arg);
            }
        }
    }

    fn item_name(&self, item: Item) -> &str {
        match item {
            Item::Struct(id) => &self.program.structs[id].name,
            Item::Enum(id) => &self.program.enums[id].name,
        }
    }

    fn qualified(&self, item: Item) -> String {
        let module = match item {
            Item::Struct(id) => Some(self.program.structs[id].module),
            Item::Enum(id) => self.program.enums[id].module,
        };
        let name = self.item_name(item);
        match module.map(|m| self.program.modules[m].as_str()) {
            Some("") | None => name.to_string(),
            Some(module) => format!("{module}.{name}"),
        }
    }

    fn write_struct(&self, out: &mut String, id: usize) {
        let s = &self.program.structs[id];
        let _ = writeln!(
            out,
            "export interface {}{} {{",
            s.name,
            type_args(&s.type_params)
        );
        for field in &s.fields {
            let _ = writeln!(
                out,
                "  {}: {};",
                field.name,
                self.ts(field.ty, &s.type_params)
            );
        }
        out.push_str("}\n");
    }

    fn write_enum(&self, out: &mut String, id: usize) {
        let e = &self.program.enums[id];
        let _ = write!(out, "export type {}{} =", e.name, type_args(&e.type_params));
        if e.variants.iter().all(|v| v.fields.is_empty()) {
            let names: Vec<String> = e.variants.iter().map(|v| quote(&v.name)).collect();
            let _ = writeln!(out, " {};", names.join(" | "));
            return;
        }
        out.push('\n');
        for (i, v) in e.variants.iter().enumerate() {
            let value = match v.fields.as_slice() {
                [] => String::new(),
                [one] => format!("; value: {}", self.ts(*one, &e.type_params)),
                many => {
                    let parts: Vec<String> =
                        many.iter().map(|t| self.ts(*t, &e.type_params)).collect();
                    format!("; value: [{}]", parts.join(", "))
                }
            };
            let end = if i + 1 == e.variants.len() { ";" } else { "" };
            let _ = writeln!(out, "  | {{ kind: {}{value} }}{end}", quote(&v.name));
        }
    }

    /// The Angular services for the API functions.
    fn write_angular(&self, out: &mut String) {
        out.push_str(
            "\n\
             /** Where the server is; empty for the page's own origin. */\n\
             export const API_BASE_URL = new InjectionToken<string>('API_BASE_URL', {\n\
             \x20 providedIn: 'root',\n\
             \x20 factory: () => '',\n\
             });\n",
        );
        let mut modules: Vec<usize> = self.program.api.iter().map(|f| f.module).collect();
        modules.dedup();
        for module in modules {
            let name = &self.program.modules[module];
            let short = name.rsplit('.').next().unwrap_or(name);
            let _ = write!(
                out,
                "\n/**\n\
                 \x20* The API functions of `{name}`. A function that returns `Err` fails\n\
                 \x20* with status 422 and the error as `HttpErrorResponse.error`.\n\
                 \x20*/\n\
                 @Injectable({{ providedIn: 'root' }})\n\
                 export class {}Client {{\n\
                 \x20 private readonly http = inject(HttpClient);\n\
                 \x20 private readonly base = inject(API_BASE_URL);\n",
                pascal_case(short)
            );
            for f in self.program.api.iter().filter(|f| f.module == module) {
                let params: Vec<String> = f
                    .params
                    .iter()
                    .map(|(p, ty)| format!("{}: {}", ts_name(p), self.ts(*ty, &[])))
                    .collect();
                let body: Vec<String> = f
                    .params
                    .iter()
                    .map(|(p, _)| {
                        let local = ts_name(p);
                        if local == *p {
                            local
                        } else {
                            format!("{p}: {local}")
                        }
                    })
                    .collect();
                let body = if body.is_empty() {
                    "{}".to_string()
                } else {
                    format!("{{ {} }}", body.join(", "))
                };
                let result = self.api_result(f.ret);
                let _ = write!(
                    out,
                    "\n  {}({}): Observable<{result}> {{\n\
                     \x20   return this.http.post<{result}>(`${{this.base}}/api/{}`, {body});\n\
                     \x20 }}\n",
                    ts_name(&camel_case(&f.name)),
                    params.join(", "),
                    f.name,
                );
            }
            out.push_str("}\n");
        }
    }

    /// What an API function's response holds: `Ok`'s value for a `Result`.
    fn api_result(&self, ret: Type) -> String {
        if let Type::Named(id) = ret {
            let named = self.program.types.get(id);
            if named.def == Def::Enum(EnumId(1)) {
                return self.ts(named.args[0], &[]);
            }
        }
        self.ts(ret, &[])
    }

    /// A Brim type in TypeScript. `params` names the type parameters.
    fn ts(&self, ty: Type, params: &[String]) -> String {
        match ty {
            Type::I64 | Type::I32 | Type::U8 | Type::U64 | Type::F64 => "number".into(),
            Type::Bool => "boolean".into(),
            Type::String => "string".into(),
            Type::Void | Type::Error => "null".into(),
            Type::Param(i) => params[i as usize].clone(),
            Type::Named(id) => {
                let named = self.program.types.get(id);
                let args: Vec<String> = named.args.iter().map(|t| self.ts(*t, params)).collect();
                match named.def {
                    // A box is only a way to store a value; JSON holds the value.
                    Def::Box => args[0].clone(),
                    // JSON has no sets: a set is sent as a list.
                    Def::Set => format!("Array<{}>", args[0]),
                    Def::Tuple => format!("[{}]", args.join(", ")),
                    Def::Fn => {
                        let (ret, params) = args.split_last().expect("a return type");
                        let params: Vec<String> = params
                            .iter()
                            .enumerate()
                            .map(|(i, p)| format!("a{i}: {p}"))
                            .collect();
                        let ret = if ret == "null" { "void" } else { ret.as_str() };
                        format!("(({}) => {ret})", params.join(", "))
                    }
                    Def::List => {
                        if args[0].contains(['|', ' ']) {
                            format!("Array<{}>", args[0])
                        } else {
                            format!("{}[]", args[0])
                        }
                    }
                    Def::Map => match named.args[0] {
                        Type::I64 | Type::I32 | Type::U8 | Type::U64 => {
                            format!("Record<number, {}>", args[1])
                        }
                        Type::Bool => format!("Partial<Record<\"true\" | \"false\", {}>>", args[1]),
                        _ => format!("Record<string, {}>", args[1]),
                    },
                    Def::Enum(EnumId(0)) => format!("{} | null", args[0]),
                    Def::Enum(EnumId(1)) => format!(
                        "{{ kind: \"Ok\"; value: {} }} | {{ kind: \"Err\"; value: {} }}",
                        args[0], args[1]
                    ),
                    Def::Struct(StructId(i)) => {
                        format!("{}{}", self.program.structs[i].name, type_args(&args))
                    }
                    Def::Enum(EnumId(i)) => {
                        format!("{}{}", self.program.enums[i].name, type_args(&args))
                    }
                }
            }
        }
    }
}

fn type_args(args: &[String]) -> String {
    if args.is_empty() {
        String::new()
    } else {
        format!("<{}>", args.join(", "))
    }
}

/// `notes_api` as `NotesApi`.
fn pascal_case(name: &str) -> String {
    name.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or(String::new(), |c| {
                c.to_uppercase().chain(chars).collect::<String>()
            })
        })
        .collect()
}

/// `create_note` as `createNote`.
fn camel_case(name: &str) -> String {
    let pascal = pascal_case(name);
    let mut chars = pascal.chars();
    chars.next().map_or(String::new(), |c| {
        c.to_lowercase().chain(chars).collect::<String>()
    })
}

/// A name that TypeScript reserves gets a `_` at the end.
fn ts_name(name: &str) -> String {
    const RESERVED: &[&str] = &[
        "break",
        "case",
        "catch",
        "class",
        "const",
        "continue",
        "debugger",
        "default",
        "delete",
        "do",
        "else",
        "enum",
        "export",
        "extends",
        "false",
        "finally",
        "for",
        "function",
        "if",
        "import",
        "in",
        "instanceof",
        "new",
        "null",
        "return",
        "super",
        "switch",
        "this",
        "throw",
        "true",
        "try",
        "typeof",
        "var",
        "void",
        "while",
        "with",
        "yield",
        "let",
        "static",
        "implements",
        "interface",
        "package",
        "private",
        "protected",
        "public",
        "await",
    ];
    if RESERVED.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

fn quote(s: &str) -> String {
    format!("\"{s}\"")
}

