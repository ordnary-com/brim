#!/bin/sh
# Prints the Homebrew formula for a release, using its SHA256SUMS:
#
#   scripts/homebrew-formula.sh 0.1.1 > Formula/brim.rb   (in ordnary-com/homebrew-tap)
set -eu
version="${1#v}"
base="https://github.com/ordnary-com/brim/releases/download/v$version"
sums=$(curl -fsSL "$base/SHA256SUMS")
sum() {
    echo "$sums" | grep " brim-$version-$1.tar.gz\$" | cut -d ' ' -f 1
}
mac_arm=$(sum macos-aarch64-native)
linux_x86=$(sum linux-x86_64-native)
linux_arm=$(sum linux-aarch64)
[ -n "$mac_arm" ] && [ -n "$linux_x86" ] && [ -n "$linux_arm" ] || {
    echo "error: SHA256SUMS of $version lacks an archive" >&2
    exit 1
}
cat <<FORMULA
# Generated by scripts/homebrew-formula.sh in ordnary-com/brim; do not edit.
class Brim < Formula
  desc "Brim, the Ordnary programming language"
  homepage "https://ordnary-com.github.io/brim/"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/brim-$version-macos-aarch64-native.tar.gz"
      sha256 "$mac_arm"
    end
  end

  on_linux do
    on_intel do
      url "$base/brim-$version-linux-x86_64-native.tar.gz"
      sha256 "$linux_x86"
    end
    on_arm do
      url "$base/brim-$version-linux-aarch64.tar.gz"
      sha256 "$linux_arm"
    end
  end

  def install
    bin.install "brim"
  end

  test do
    (testpath/"hello.brim").write <<~BRIM
      fn main() {
          print("hello")
      }
    BRIM
    assert_equal "hello\\n", shell_output("#{bin}/brim run hello.brim")
  end
end
FORMULA
